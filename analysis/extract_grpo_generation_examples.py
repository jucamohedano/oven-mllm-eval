#!/usr/bin/env python3
"""Extract validation generation examples from offline wandb run dirs.

verl logs a validation ``generations`` wandb.Table as media JSON under
``<run_dir>/files/media/table/val/generations_<step>_<hash>.table.json`` with
columns ``step, input_1, output_1, score_1, ... input_N, output_N, score_N``.
This pulls a couple of representative examples per run (one high-scoring, one
low-scoring) from the latest logged validation table and writes a Markdown doc
for the thesis.

Reproducible: to add trav08 once it finishes, re-sync its media dir and re-run.
Note the table data lives in the media JSON, NOT the ``.wandb`` datastore, so the
``files/media/table/val/`` directory must be synced from the cluster.

Usage::

    .venv/bin/python analysis/extract_grpo_generation_examples.py \
        <run_dir> [<run_dir> ...] --out viz/grpo/grpo_generation_examples.md \
        [--per-run 2] [--max-output-chars 1200]
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def short_run(run_dir: Path) -> str:
    for tag in ("agg05", "agg08", "trav08"):
        if tag in run_dir.name:
            return tag
    return run_dir.name


def latest_table(run_dir: Path) -> Path | None:
    tables = list((run_dir / "files" / "media" / "table" / "val").glob("generations_*.table.json"))
    if not tables:
        return None
    # filename embeds the step: generations_<step>_<hash>.table.json
    def step_of(p: Path) -> int:
        m = re.search(r"generations_(\d+)_", p.name)
        return int(m.group(1)) if m else -1
    return max(tables, key=step_of)


def parse_examples(table_path: Path) -> tuple[int, list[dict]]:
    """Return (max_step, examples-from-max-step).

    The validation table accumulates one row per validation invocation, each row
    holding 20 examples. We keep only the rows at the latest step so examples
    reflect the final trained policy, not earlier checkpoints.
    """
    d = json.loads(table_path.read_text())
    cols = d["columns"]
    idx = {c: i for i, c in enumerate(cols)}
    n = sum(1 for c in cols if c.startswith("input_"))
    rows = d.get("data", [])
    row_steps = [int(r[idx["step"]]) if "step" in idx else -1 for r in rows]
    max_step = max(row_steps) if row_steps else -1

    examples: list[dict] = []
    for row, rstep in zip(rows, row_steps):
        if rstep != max_step:
            continue
        for k in range(1, n + 1):
            ik, ok, sk = f"input_{k}", f"output_{k}", f"score_{k}"
            if ik not in idx:
                continue
            inp = row[idx[ik]]
            out = row[idx[ok]]
            sc = row[idx[sk]]
            if inp is None or out is None:
                continue
            try:
                sc = float(sc)
            except (TypeError, ValueError):
                sc = None
            examples.append({"input": str(inp), "output": str(out), "score": sc})
    return max_step, examples


def pick(examples: list[dict], per_run: int) -> list[dict]:
    scored = [e for e in examples if e["score"] is not None]
    if not scored:
        return examples[:per_run]
    scored.sort(key=lambda e: e["score"], reverse=True)
    picks = [scored[0]]  # best
    if per_run >= 2:
        picks.append(scored[-1])  # worst
    for e in scored[1:-1]:  # fill middle if more requested
        if len(picks) >= per_run:
            break
        picks.append(e)
    return picks[:per_run]


def fmt_block(ex: dict, max_out: int) -> str:
    out = ex["output"].strip()
    if len(out) > max_out:
        out = out[:max_out].rstrip() + " […]"
    score = "n/a" if ex["score"] is None else f"{ex['score']:.3f}"
    return (
        f"**Reward:** {score}\n\n"
        f"*Prompt:*\n\n```\n{ex['input'].strip()}\n```\n\n"
        f"*Model output:*\n\n```\n{out}\n```\n"
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("run_dirs", nargs="+", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--per-run", type=int, default=2)
    ap.add_argument("--max-output-chars", type=int, default=1200)
    args = ap.parse_args()

    md = [
        "# GRPO validation generation examples",
        "",
        "Auto-generated by `analysis/extract_grpo_generation_examples.py`. "
        "Examples are drawn from the latest logged validation table per run "
        "(one highest-reward, one lowest-reward). Validation uses the **standard** "
        "prompt for all runs, so no `<traversal>` structure is expected in outputs.",
        "",
    ]
    for run_dir in args.run_dirs:
        tag = short_run(run_dir)
        table = latest_table(run_dir)
        md.append(f"## {tag}")
        if table is None:
            md.append(
                f"_No validation media table found under_ `{run_dir}/files/media/table/val/`. "
                "Sync the run's `files/media/` directory from the cluster and re-run.\n"
            )
            print(f"[warn] no media table for {tag} ({run_dir})")
            continue
        step, examples = parse_examples(table)
        md.append(f"_Source: `{table.name}` (validation step {step}), "
                  f"{len(examples)} examples in table._\n")
        for i, ex in enumerate(pick(examples, args.per_run), start=1):
            md.append(f"### {tag} — example {i}")
            md.append(fmt_block(ex, args.max_output_chars))
        print(f"[ok] {tag}: {len(examples)} examples, step {step}")

    args.out.write_text("\n".join(md) + "\n")
    print(f"[md] wrote {args.out}")


if __name__ == "__main__":
    main()
